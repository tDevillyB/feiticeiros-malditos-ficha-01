function makeBlankProficiency(
  id: string,
  name: string,
  attribute: AttributeKey,
  isCustomName = false
): ProficiencyRollEntry {
  return {
    id,
    name,
    isCustomName,
    attribute,
    other: 0,
    trained: false,
    mastered: false,
    total: createCalculableField(0),
  };
}

function makeDefaultAttribute(key: AttributeKey, label: string) {
  return {
    key,
    label,
    baseValue: 10,
    bonusValue: 0,
    value: createCalculableField(10),
    modifier: createCalculableField(0),
  };
}

